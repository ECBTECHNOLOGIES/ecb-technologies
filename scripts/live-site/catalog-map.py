"""Builds docs/seo/live-site/catalog-map.js for the ecb-speed Worker:

- CATEGORIES: the shop's main categories [slug, name]
- CATEGORY_OF: product slug -> index into CATEGORIES (for breadcrumbs and
  Product schema)
- REDIRECTS: old product slug -> new slug (product addresses that changed
  when GeniusCart regenerated slugs), from cloudflare-redirects.csv

Run again after adding many products or categories, then redeploy.
Usage: python3 -I catalog-map.py <repo-root>
"""
import csv
import json

ALIAS_JS = """
// The shop has used two slugs for most products (new ones from 14 Nov, the
// old ones again from 16 Nov). Map both, so a product keeps its category
// whichever slug is live.
for (const [a, b] of Object.entries(REDIRECTS)) {
  if (CATEGORY_OF[a] === undefined && CATEGORY_OF[b] !== undefined) CATEGORY_OF[a] = CATEGORY_OF[b];
  if (CATEGORY_OF[b] === undefined && CATEGORY_OF[a] !== undefined) CATEGORY_OF[b] = CATEGORY_OF[a];
}
"""
import re
import sys
import urllib.request

B = "https://www.ecbtechkenya.com"
CATEGORIES = [
    ("laptops", "Laptops"),
    ("smartphones", "Smartphones"),
    ("Computing-Accessories", "PC Accessories"),
    ("TV-and-Home-Appliances", "TVs & Home Appliances"),
    ("Mobile-Accessories", "Mobile Accessories"),
    ("printers", "Printers"),
    ("gaming", "Gaming"),
    ("Audio-Accessories", "Audio Accessories"),
]


def get(url, tries=4):
    # The shop sometimes cuts large pages short; retry.
    for attempt in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (ECB catalog map)", "Cookie": "laravel_session=x"})
            with urllib.request.urlopen(req, timeout=120) as r:
                return r.read().decode("utf-8", "replace")
        except Exception as e:  # IncompleteRead, timeouts
            if attempt == tries - 1:
                raise
            print("retry", url, type(e).__name__, file=sys.stderr)


def main(root):
    category_of = {}
    for i, (slug, name) in enumerate(CATEGORIES):
        html = get(f"{B}/category/{slug}?pageby=10000")
        items = set(re.findall(r'href="https://www\.ecbtechkenya\.com/item/([A-Za-z0-9-]+)"', html)) - {"compare", "show"}
        new = 0
        for it in items:
            if it not in category_of:
                category_of[it] = i
                new += 1
        print(f"{name}: {len(items)} products ({new} first assigned here)")
    redirects = {}
    with open(f"{root}/docs/seo/live-site/cloudflare-redirects.csv") as fh:
        for row in csv.reader(fh):
            if len(row) < 2 or "/item/" not in row[0]:
                continue
            old = row[0].split("/item/")[1]
            new = row[1].split("/item/")[1]
            if old != new:
                redirects[old] = new
    with open(f"{root}/docs/seo/live-site/catalog-map.js", "w") as fh:
        fh.write("// Generated by scripts/live-site/catalog-map.py. Do not edit.\n")
        fh.write(f"export const CATEGORIES = {json.dumps(CATEGORIES)};\n")
        fh.write(f"export const CATEGORY_OF = {json.dumps(category_of, separators=(',', ':'))};\n")
        fh.write(f"export const REDIRECTS = {json.dumps(redirects, separators=(',', ':'))};\n")
        fh.write(ALIAS_JS)
    print(f"{len(category_of)} products mapped, {len(redirects)} redirects")


if __name__ == "__main__":
    main(sys.argv[1])
