"""Builds the merged stylesheet for the ecb-speed Worker.

Downloads the theme's stylesheets in the order the shop loads them, fixes
relative url(...) paths, moves the Google Fonts @import out (the Worker links
it from the page instead) and switches icon fonts to font-display:swap.
Writes:
  docs/seo/live-site/bundle-css.js  (module the Worker imports)
  <out-dir>/bundle.css              (plain copy, input for used-css.js)

Run again whenever the theme's CSS changes, then run used-css.js and deploy.

Usage: python3 -I build-css.py <repo-root> <out-dir>
"""
import hashlib
import json
import re
import sys
import urllib.parse
import urllib.request

BASE = "https://www.ecbtechkenya.com/assets/front/css/"
ORDER = ["bootstrap.min.css", "all.css", "slick.css", "nice-select.css", "jquery-ui.css", "animate.css",
         "toastr.min.css", "datatables.min.css", "style.css", "custom.css", "ecb-theme.css", "font.php"]


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (ECB css build)"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8", "replace")


def absolutize(css, base):
    def fix(m):
        q, u = m.group(1), m.group(2)
        if re.match(r"^(data:|https?:|//|#|/)", u, re.I):
            return m.group(0)
        return f"url({q}{urllib.parse.urljoin(base, u)}{q})"
    return re.sub(r"url\(\s*(['\"]?)([^'\")]+)\1\s*\)", fix, css)


def main(root, out_dir):
    home = get("https://www.ecbtechkenya.com/user/login")  # a page the Worker leaves as is
    theme_v = (re.search(r"ecb-theme\.css\?v=([\w.-]+)", home) or [None, ""])[1]
    font = (re.search(r"font\.php\?font_familly=([\w+%-]+)", home) or [None, "Roboto"])[1]
    parts = []
    for name in ORDER:
        f = name
        if name == "ecb-theme.css" and theme_v:
            f = f"ecb-theme.css?v={theme_v}"
        if name == "font.php":
            f = f"font.php?font_familly={font}"
        css = get(BASE + f)
        css = re.sub(r"@import\s+url\([^)]*\)\s*;?", "", css)
        css = re.sub(r"@charset[^;]*;", "", css)
        css = re.sub(r"font-display:\s*block", "font-display:swap", css)
        parts.append(f"/* {name} */\n" + absolutize(css, BASE + f))
    bundle = "\n".join(parts)
    h = hashlib.sha256(bundle.encode()).hexdigest()[:12]
    with open(f"{out_dir}/bundle.css", "w") as fh:
        fh.write(bundle)
    with open(f"{root}/docs/seo/live-site/bundle-css.js", "w") as fh:
        fh.write("// Generated by scripts/live-site/build-css.py. Do not edit.\n")
        fh.write(f"export const BUNDLE_HASH = {json.dumps(h)};\n")
        fh.write(f"export const THEME_VERSION = {json.dumps(theme_v)};\n")
        fh.write(f"export const BUNDLE_CSS = {json.dumps(bundle)};\n")
    print(f"bundle {len(bundle)} bytes, hash {h}, ecb-theme v={theme_v}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
